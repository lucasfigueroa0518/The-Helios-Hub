// Measures the advance width of every printable ASCII character in the bundled fonts and writes
// explainers/world-kit/metrics.js (Explainers 3.2, EX3-80), so the kit's typeset() breaks lines
// from real widths instead of guessing them (the 3.1 definition card's uneven spacing).
//   node explainers/design/tools/measure-fonts.mjs
import { createServer } from 'node:http';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const FACES = [
  { key: 'roboto-400', family: 'Roboto', weight: 400, file: 'design/fonts/Roboto-400.woff2' },
  { key: 'roboto-500', family: 'Roboto', weight: 500, file: 'design/fonts/Roboto-500.woff2' },
  { key: 'roboto-700', family: 'Roboto', weight: 700, file: 'design/fonts/Roboto-700.woff2' },
  { key: 'pragmatica-700', family: 'Pragmatica Extended', weight: 700, file: 'design/fonts/PragmaticaExtended-Bold.otf' },
];
const css = FACES.map((f) => `@font-face{font-family:'${f.family}';font-weight:${f.weight};src:url('/${f.file}')}`).join('');
const srv = createServer((req, res) => {
  if (req.url === '/') {
    res.writeHead(200, { 'content-type': 'text/html' });
    res.end(`<!doctype html><style>${css}</style><body>${FACES.map((f) => `<span style="font-family:'${f.family}';font-weight:${f.weight}">x</span>`).join('')}</body>`);
    return;
  }
  try {
    const p = join(root, decodeURIComponent(req.url));
    res.writeHead(200, { 'content-type': extname(p) === '.otf' ? 'font/otf' : 'font/woff2' });
    res.end(readFileSync(p));
  } catch {
    res.writeHead(404);
    res.end();
  }
}).listen(0);
await new Promise((ok) => srv.on('listening', ok));
const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto(`http://127.0.0.1:${srv.address().port}/`);
await page.evaluate(() => document.fonts.ready);
const metrics = await page.evaluate((faces) => {
  const c = document.createElement('canvas').getContext('2d');
  const out = {};
  for (const f of faces) {
    c.font = `${f.weight} 1000px '${f.family}'`;
    const w = {};
    for (let i = 32; i < 127; i++) w[String.fromCharCode(i)] = Math.round(c.measureText(String.fromCharCode(i)).width);
    // a check that the face really loaded: the fallback's 'W' differs
    out[f.key] = { family: f.family, weight: f.weight, w, loaded: document.fonts.check(`${f.weight} 20px '${f.family}'`) };
  }
  return out;
}, FACES);
await browser.close();
srv.close();
for (const [k, m] of Object.entries(metrics)) if (!m.loaded) throw new Error(`${k} did not load`);
const body = Object.fromEntries(Object.entries(metrics).map(([k, m]) => [k, { family: m.family, weight: m.weight, w: m.w }]));
writeFileSync(
  join(root, 'world-kit', 'metrics.js'),
  `// Advance widths of the bundled fonts, per 1000 px of font size (Explainers 3.2, EX3-80). Generated by\n// explainers/design/tools/measure-fonts.mjs; do not edit by hand. typeset() breaks lines from these.\n\nexport const METRICS = ${JSON.stringify(body)};\n`,
);
console.log(Object.keys(body).join(', '));
