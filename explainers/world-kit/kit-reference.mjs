// The kit reference, GENERATED from the kit's own exports and doc comments (4.2 cost lever): a compact
// map a builder reads instead of re-reading set.js or lens.js. Never edit KIT-REFERENCE.md by hand;
// it is rebuilt from source, so it cannot drift.
//
//   node kit-reference.mjs [out.md]      (default: KIT-REFERENCE.md beside this script)
//   import { kitReference } from './kit-reference.mjs'   → { markdown, modules: { file: [names] } }
//
// For every module a frame imports: each export's signature (its options and their defaults, as
// written), the first sentence of its doc comment (and its "Returns" sentence when it has one), and
// for each exported list or table its ids or keys. The full source stays the authority for edge cases.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
/** The modules a frame or the world draws with, in reading order. */
export const REFERENCE_MODULES = ['core.js', 'draw.js', 'motion.js', 'lens.js', 'light.js', 'set.js', 'shots.js', 'cast.js', 'animals.js', 'outfits.js', 'space.js', 'objects.js', 'connect.js', 'setlock.js', 'glass.js', 'layout.js', 'explain.js', 'cards.js', 'props.js', 'seams.js', 'mark.js', 'close.js', 'examples.js'];

/**
 * The exports builders looked up in kit source (transcript c3ceee5e, cost fix 2): their whole doc
 * comment (option tables, return shapes) is printed under their line, not only its first sentence.
 */
export const FULL_DOCS = new Set(['object', 'lensObject', 'worldObject', 'shotFrame', 'shotAt', 'shotLensAt', 'lensOnto', 'carry', 'setBuilder', 'room', 'critter', 'critterAt', 'act', 'actAt', 'propFrom', 'propScale', 'outfitLayers', 'keepoutClip', 'softShape', 'colourScript', 'spill', 'paintOrder', 'conceptNode', 'dictionaryCard', 'uiIcon', 'counter', 'underlay', 'route', 'tagProblems', 'animal', 'animalFrom']);
/** Spec comment blocks (`// ── Title` and the `//` lines under it) printed whole: data shapes no export's doc carries. */
export const SPEC_BLOCKS = [{ file: 'shots.js', start: '// ── Cut grammar' }];

/** The doc comment right above position i with its line breaks kept (stars stripped), or ''. */
function docRawBefore(src, i) {
  const before = src.slice(0, i).replace(/\s+$/, '');
  if (!before.endsWith('*/')) return '';
  const start = before.lastIndexOf('/**');
  if (start < 0) return '';
  return before.slice(start + 3, -2).split('\n').map((l) => l.replace(/^\s*\*\s?/, '').trimEnd()).filter((l, k, a) => l || (k > 0 && k < a.length - 1)).join('\n').trim();
}

const clip = (s, n) => (s.length > n ? `${s.slice(0, n - 1)}…` : s);
const squash = (s) => s.replace(/\s+/g, ' ').trim();

/** The doc comment right above position i (its text, stars stripped), or ''. */
function docBefore(src, i) {
  const before = src.slice(0, i).replace(/\s+$/, '');
  if (!before.endsWith('*/')) return '';
  const start = before.lastIndexOf('/**');
  if (start < 0) return '';
  return squash(before.slice(start + 3, -2).replace(/^\s*\*\s?/gm, ' ').replace(/@(param|returns|typedef)\b[^\n]*/g, ''));
}
/** The doc's first sentence, and its Returns sentence when that is a different one. */
function gist(doc) {
  if (!doc) return '';
  // the first sentence (a colon runs on: what follows it is the content)
  const first = (doc.match(/^.*?\.(\s|$)/)?.[0] ?? doc).trim();
  const ret = doc.match(/(Returns|returns|→)[^.]*\./)?.[0];
  return clip(squash(ret && !first.includes(ret) ? `${first} ${ret}` : first), 150);
}
/** The balanced (...) starting at i: a function's parameter list. */
function parens(src, i) {
  let d = 0;
  for (let k = i; k < src.length; k++) {
    if (src[k] === '(') d++;
    else if (src[k] === ')' && --d === 0) return src.slice(i, k + 1);
  }
  return '()';
}
/** A short summary of an exported value: a list's items, a table's keys, a number or string. */
function valueOf(v) {
  if (typeof v === 'function') return null;
  if (Array.isArray(v)) return `[${clip(v.map((x) => (typeof x === 'object' ? JSON.stringify(x) : String(x))).join(", "), 1100)}]`;
  if (v && typeof v === 'object') {
    const keys = Object.keys(v);
    return `{ ${clip(keys.join(", "), 500)} }${keys.length > 6 ? ` (${keys.length} keys)` : ''}`;
  }
  return clip(JSON.stringify(v) ?? String(v), 120);
}

/** The reference: { markdown, modules: { file: [export names] } }. */
export async function kitReference({ dir = HERE } = {}) {
  // the CDN freehand import falls back offline (draw.js), so the modules load in plain Node
  const lines = ['# KIT-REFERENCE (generated by `node assets/kit/kit-reference.mjs`; never edit by hand)', '', 'One line per export: `name(signature)`, what it is; the most used ones with their whole doc. Lists show their ids. When this page does not explain something, Read or Grep the kit source (assets/kit).', ''];
  const modules = {};
  for (const file of REFERENCE_MODULES) {
    const full = path.join(dir, file);
    if (!fs.existsSync(full)) continue;
    const src = fs.readFileSync(full, 'utf8');
    let mod = {};
    try { mod = await import(pathToFileURL(full).href); } catch (e) { mod = {}; lines.push(`> ${file} did not load here: ${e?.message ?? e}`); }
    const head = src.match(/^\/\/ (.*)$/m)?.[1] ?? '';
    lines.push(`## ${file}`, head ? `_${clip(squash(head), 200)}_` : '', '');
    const names = [];
    const seen = new Set();
    const re = /^export\s+(?:async\s+)?(function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm;
    let m;
    while ((m = re.exec(src))) {
      const [, kind, name] = m;
      if (seen.has(name)) continue;
      seen.add(name);
      names.push(name);
      const doc = gist(docBefore(src, m.index));
      let sig = '';
      if (kind.startsWith('function')) sig = squash(parens(src, src.indexOf('(', m.index)));
      else {
        // an arrow function: its parameter list; a value: its summary
        const rest = src.slice(m.index, m.index + 400);
        const arrow = rest.match(/=\s*(?:async\s+)?(\([^)]*\)|[A-Za-z_$][\w$]*)\s*=>/);
        if (arrow && typeof mod[name] === 'function') sig = squash(arrow[1].startsWith('(') ? arrow[1] : `(${arrow[1]})`);
      }
      const val = sig ? null : valueOf(mod[name]);
      const body = sig ? `\`${name}${clip(sig, 240)}\`` : `\`${name}\`${val ? ` = ${val}` : ''}`;
      const full = FULL_DOCS.has(name) ? docRawBefore(src, m.index) : '';
      if (full && full.length > doc.length + 20) lines.push(`- ${body}`, ...clip(full, 1200).split('\n').map((l) => `    ${l}`));
      else lines.push(`- ${body}${doc ? ` — ${doc}` : ''}`);
    }
    for (const b of SPEC_BLOCKS.filter((x) => x.file === file)) {
      const at = src.indexOf(b.start);
      if (at < 0) continue;
      const block = [];
      for (const l of src.slice(at).split('\n')) {
        if (!/^\s*\/\//.test(l)) break;
        block.push(l.replace(/^\s*\/\/ ?/, '').replace(/^─+\s*/, ''));
      }
      lines.push('', '```', ...block.filter((l, k) => l || k > 0), '```', '');
    }
    // re-exports: export { a, b as c } [from '…']
    for (const r of src.matchAll(/^export\s*\{([^}]+)\}(?:\s*from\s*'([^']+)')?/gm)) {
      for (const part of r[1].split(',')) {
        const name = part.trim().split(/\s+as\s+/).pop();
        if (!name || seen.has(name)) continue;
        seen.add(name);
        names.push(name);
        const val = valueOf(mod[name]);
        lines.push(`- \`${name}\`${val ? ` = ${val}` : ''} — re-exported${r[2] ? ` from ${r[2]}` : ''}`);
      }
    }
    // `export * from …` and anything else the module exports at runtime
    const star = [...src.matchAll(/^export\s*\*\s*from\s*'([^']+)'/gm)].map((x) => x[1]);
    const more = Object.keys(mod).filter((n) => !seen.has(n));
    if (more.length) {
      names.push(...more);
      lines.push(`- re-exported${star.length ? ` from ${star.join(', ')}` : ''}: ${more.map((n) => (typeof mod[n] === 'function' ? `\`${n}()\`` : `\`${n}\``)).join(', ')}`);
    }
    modules[file] = names;
    lines.push('');
  }
  return { markdown: lines.filter((l, i, a) => !(l === '' && a[i - 1] === '')).join('\n'), modules };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const out = process.argv[2] ?? path.join(HERE, 'KIT-REFERENCE.md');
  const { markdown } = await kitReference();
  fs.writeFileSync(out, markdown);
  console.log(JSON.stringify({ out, chars: markdown.length, tokensApprox: Math.round(markdown.length / 4) }));
}
