/**
 * Build the logo bank (lib/social-hub/logo-bank.ts): one licensed Commons logo
 * per blue-chip and affiliated company, resolved from its pinned Wikidata QID
 * with the cover card's rules (lib/social/photos/logo.ts fetchLogo).
 *
 *   npx tsx scripts/social_logo_bank.ts
 *
 * Plain web fetches to Wikidata and Commons, no model call. Writes the PNGs to
 * lib/social/render/assets/logos/ and the manifest to
 * lib/social-hub/logo-bank.generated.ts. Read the diff before it ships:
 * Wikidata is open to edits.
 */
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { LOGO_COMPANIES, type CompanyRef } from '@/lib/social-hub/blue-chip-players';
import { LOGO_DIR, REVIEW_REJECTS, type BuiltEntry } from '@/lib/social-hub/logo-bank';
import { fetchLogo } from '@/lib/social/photos/logo';

const USER_AGENT = 'HeliosHub/1.0 (+https://heliosgroup.ai; helios@heliosgroup.ai)';
const PNG_MAGIC = Buffer.from([0x89, 0x50, 0x4e, 0x47]);
const pause = (ms: number) => new Promise((r) => setTimeout(r, ms));
const root = process.cwd();

async function build(c: CompanyRef): Promise<BuiltEntry> {
  const base = { id: c.id, name: c.name, qid: c.qid };
  const res = await fetchLogo(c.qid, c.name, { softwareLicences: true });
  if (!res.photo) return { status: 'missing', ...base, reason: res.reason };
  const rejected = REVIEW_REJECTS[c.id];
  if (rejected?.provenance === `File:${res.file}`) {
    rmSync(path.join(root, `${LOGO_DIR}/${c.id}.png`), { force: true });
    return { status: 'missing', ...base, reason: `rejected in review: ${rejected.reason}` };
  }
  const r = await fetch(res.photo.url, { headers: { 'User-Agent': USER_AGENT } });
  const png = Buffer.from(await r.arrayBuffer());
  if (!r.ok || !png.subarray(0, 4).equals(PNG_MAGIC)) return { status: 'missing', ...base, reason: `download was not a PNG (HTTP ${r.status})` };
  const file = `${LOGO_DIR}/${c.id}.png`;
  writeFileSync(path.join(root, file), png);
  return {
    status: 'ok',
    ...base,
    file,
    width: res.photo.width ?? 0,
    height: res.photo.height ?? 0,
    plate: res.photo.plate === 'dark' ? 'dark' : 'light',
    credit: res.photo.credit,
    provenance: `File:${res.file}`,
  };
}

async function main() {
  mkdirSync(path.join(root, LOGO_DIR), { recursive: true });
  const entries: BuiltEntry[] = [];
  for (const c of LOGO_COMPANIES) {
    const e = await build(c);
    entries.push(e);
    console.log(e.status === 'ok' ? `  ✓ ${c.name}: ${e.provenance} (${e.width}×${e.height}, ${e.plate} plate)` : `  ✗ ${c.name}: ${e.reason}`);
    await pause(400);
  }
  const target = path.join(root, 'lib/social-hub/logo-bank.generated.ts');
  writeFileSync(
    target,
    [
      '// Generated by scripts/social_logo_bank.ts (npx tsx scripts/social_logo_bank.ts). Do not edit by hand.',
      `// Built ${new Date().toISOString().slice(0, 10)} from Wikidata P154 and Wikimedia Commons.`,
      "import type { BuiltEntry } from './logo-bank';",
      '',
      `export const BUILT_LOGOS: readonly BuiltEntry[] = ${JSON.stringify(entries, null, 2)};`,
      '',
    ].join('\n'),
  );
  const ok = entries.filter((e) => e.status === 'ok').length;
  console.log(`Wrote ${path.relative(root, target)}: ${ok} of ${entries.length} logos.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
