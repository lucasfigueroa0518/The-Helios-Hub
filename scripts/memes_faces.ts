/**
 * Detect the human faces in every catalog template once and freeze them into
 * lib/memes/faces.generated.ts (ME-12: a label never covers a face). The same
 * MediaPipe detector the photo step uses: faces, never identities. Cartoon
 * faces are not detected; geometry.ts places those slots by hand.
 *
 *   npx tsx scripts/memes_faces.ts
 */
import fs from 'node:fs';
import path from 'node:path';

import { TEMPLATE_CATALOG } from '@/lib/memes/catalog';
import { detectFacesLive } from '@/lib/social/photos/faces';

async function main() {
  const dir = path.join(process.cwd(), 'lib/memes/assets/templates');
  const urls = TEMPLATE_CATALOG.map((t) => {
    const mime = t.image.endsWith('.png') ? 'image/png' : 'image/jpeg';
    return `data:${mime};base64,${fs.readFileSync(path.join(dir, t.image)).toString('base64')}`;
  });
  const found = await detectFacesLive(urls);
  const faces: Record<string, Array<{ x: number; y: number; w: number; h: number }>> = {};
  TEMPLATE_CATALOG.forEach((t, i) => {
    const boxes = found.get(urls[i]!);
    if (boxes === null || boxes === undefined) throw new Error(`${t.id}: image did not load`);
    faces[t.id] = boxes.map((b) => ({ x: +b.x.toFixed(4), y: +b.y.toFixed(4), w: +b.w.toFixed(4), h: +b.h.toFixed(4) }));
    console.log(`${t.id}: ${boxes.length} face(s)`);
  });
  const target = path.join(process.cwd(), 'lib/memes/faces.generated.ts');
  fs.writeFileSync(
    target,
    [
      '// Generated by scripts/memes_faces.ts. Do not edit by hand.',
      '// Human faces in each template (0–1 of the image), MediaPipe face detector.',
      '',
      `export const TEMPLATE_FACES: Readonly<Record<string, ReadonlyArray<{ x: number; y: number; w: number; h: number }>>> = ${JSON.stringify(faces, null, 2)};`,
      '',
    ].join('\n'),
  );
  console.log(`Wrote ${path.relative(process.cwd(), target)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
